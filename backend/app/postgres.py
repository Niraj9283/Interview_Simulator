"""PostgreSQL support for the repository's parameterized qmark SQL queries."""
from datetime import datetime
import psycopg
from psycopg.rows import dict_row


def api_row(cursor):
    make_row = dict_row(cursor)
    def convert(values):
        row = make_row(values)
        return {key: value.isoformat() if isinstance(value, datetime) else value
                for key, value in row.items()}
    return convert


class RepositoryCursor(psycopg.Cursor):
    def execute(self, query, params=None, **kwargs):
        # Only repository-owned SQL reaches this adapter. User values remain
        # separate bound parameters, including values containing '?' or '%'.
        query = query.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
        if params is not None:
            query = query.replace("%", "%%").replace("?", "%s")
        return super().execute(query, params, **kwargs)


def connect(database_url):
    conn = psycopg.connect(
        database_url, row_factory=api_row, cursor_factory=RepositoryCursor,
        connect_timeout=5,
    )
    conn.execute("SET LOCAL statement_timeout = 10000")
    return conn
